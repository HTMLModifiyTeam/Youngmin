function randomUnicode(length) {
  let result = "";
  while (result.length < length) {
    const code = Math.floor(Math.random() * 0x10000); // U+0000 - U+FFFF
    if (code >= 0xD800 && code <= 0xDFFF) continue;
    result += String.fromCharCode(code);
  }
  return result;
}

